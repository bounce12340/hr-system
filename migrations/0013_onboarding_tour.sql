-- 0013：新手引導狀態（人資回饋，原規格未涵蓋）。
--
-- 需求：初次使用者不知道從哪裡開始。首次登入時自動跑一次互動導覽，跑完（或
-- 主動略過）之後就不再自動出現，但可從選單「重看導覽」隨時再跑。
--
-- 為什麼存在資料庫而不是 localStorage：
--   localStorage 綁瀏覽器，同一個人換電腦、換手機、清快取都會重新被導覽一次。
--   在公司環境裡「換裝置」是常態（辦公室桌機＋手機查課表），重複出現會變成
--   干擾而不是幫助。存在 users 上則跟著人走，且與既有的 must_change_password
--   同屬「這個帳號的一次性引導狀態」，放在一起是一致的。
--
-- 存時間戳而不是布林值：日後要知道「這批人是什麼時候被導覽的」「導覽改版後
-- 誰該重看」都需要時間；布林值當下省事，之後補不回來。NULL = 尚未完成。
ALTER TABLE users ADD COLUMN tour_completed_at TEXT;
